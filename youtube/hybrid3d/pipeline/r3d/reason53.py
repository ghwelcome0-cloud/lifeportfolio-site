def main():
    dry = "--dry" in sys.argv
    d = json.load(open(SRC))
    rows = d["rows"]
    miss = [r["sid"] for r in rows if not (r.get("reason") or "").strip()]
    unknown = sorted(set(R) - set(miss))
    absent = sorted(set(miss) - set(R))
    if unknown:
        raise SystemExit(f"keys not missing in source: {unknown}")
    if absent:
        raise SystemExit(f"still missing, no narrative written: {absent}")
    bad = [k for k, v in R.items() if not (60 <= len(v) <= 130)]
    if bad:
        raise SystemExit(f"length out of 60-130: {[(k, len(R[k])) for k in bad]}")
    n = 0
    for r in rows:
        if r["sid"] in R and not (r.get("reason") or "").strip():
            r["reason"] = R[r["sid"]]
            n += 1
    print(f"filled {n} / needed {len(miss)}   lengths {min(map(len,R.values()))}-{max(map(len,R.values()))}")
    if dry:
        print("dry run, nothing written")
        return
    shutil.copy2(SRC, SRC + ".bak")
    with open(SRC, "w") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    chk = json.load(open(SRC))["rows"]
    left = [r["sid"] for r in chk if not (r.get("reason") or "").strip()]
    print("rows:", len(chk), " reason still empty:", len(left))


if __name__ == "__main__":
    main()
