s(){ sed -n "/^$1/,/^$2/p" "$3" | sed '1d;$d'; }
c(){ diff <(s "$1" "$2" $R1) <(s "$3" "$4" "$O") >/dev/null || { echo "FAIL $5"; exit 1; }; }
